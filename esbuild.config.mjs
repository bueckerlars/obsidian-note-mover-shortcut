import esbuild from 'esbuild';
import path from 'node:path';
import { builtinModules } from 'node:module';
import process from 'process';
import { readLanguageCatalogs } from './scripts/read-language-catalogs.mjs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';
const languagesDir = path.resolve('languages');

function languagesPlugin() {
  return {
    name: 'languages',
    setup(build) {
      build.onResolve({ filter: /^virtual:languages$/ }, () => ({
        path: languagesDir,
        namespace: 'languages',
      }));
      build.onLoad({ filter: /.*/, namespace: 'languages' }, () => ({
        contents: `export default ${JSON.stringify(readLanguageCatalogs(languagesDir))};`,
        loader: 'js',
      }));
    },
  };
}

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ['main.ts'],
  bundle: true,
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtinModules,
  ],
  format: 'cjs',
  target: 'es2022',
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  plugins: [languagesPlugin()],
  outfile: 'main.js',
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
