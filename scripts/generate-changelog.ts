import * as fs from 'fs';
import * as path from 'path';

interface ReleaseHighlight {
  /** Lucide icon name. */
  icon: string;
  title: string;
  text: string;
}

interface ChangelogEntry {
  version: string;
  /** User-facing, shown in the release notes dialog. */
  highlights?: ReleaseHighlight[];
  /** User-facing, shown in the release notes dialog. */
  fixes?: string[];
  changes: {
    breaking?: string[];
    features?: string[];
    bugFixes?: string[];
    improvements?: string[];
    changes?: string[];
    fixes?: string[];
    performance?: string[];
  };
}

function parseChangelog(content: string): ChangelogEntry[] {
  const entries: ChangelogEntry[] = [];
  const lines = content.split('\n');

  let currentVersion = '';
  let currentChanges: ChangelogEntry['changes'] = {};
  let currentHighlights: ReleaseHighlight[] = [];
  let currentFixes: string[] = [];
  let inHighlights = false;
  let inReleaseFixes = false;

  const save = (): void => {
    entries.push({
      version: currentVersion,
      ...(currentHighlights.length > 0 && { highlights: currentHighlights }),
      ...(currentFixes.length > 0 && { fixes: currentFixes }),
      changes: { ...currentChanges },
    });
  };
  let currentSection:
    | 'breaking'
    | 'features'
    | 'bugFixes'
    | 'improvements'
    | 'changes'
    | 'fixes'
    | 'performance'
    | null = null;

  for (const line of lines) {
    // Recognize version header (e.g. "## [0.2.1]" or "## [0.1.6]")
    const versionMatch = line.match(/^##\s*\[?(\d+\.\d+\.\d+)\]?/);
    if (versionMatch) {
      const nextVersion = versionMatch[1];
      if (!nextVersion) continue;
      // Save previous version if exists
      if (currentVersion) save();

      // Start new version
      currentVersion = nextVersion;
      currentChanges = {};
      currentHighlights = [];
      currentFixes = [];
      currentSection = null;
      inHighlights = false;
      inReleaseFixes = false;
      continue;
    }

    // User-facing sections for the release notes dialog:
    //   ### Highlights        - "- lucide-icon | Title | One sentence."
    //   ### Release note fixes - "- One sentence."
    if (line.startsWith('### Highlights')) {
      inHighlights = true;
      inReleaseFixes = false;
      currentSection = null;
      continue;
    }
    if (line.startsWith('### Release note fixes')) {
      inHighlights = false;
      inReleaseFixes = true;
      currentSection = null;
      continue;
    }
    if (line.startsWith('### ')) {
      inHighlights = false;
      inReleaseFixes = false;
    }
    if (line.startsWith('- ') && (inHighlights || inReleaseFixes)) {
      const text = line.substring(2).trim();
      if (inReleaseFixes) {
        if (text) currentFixes.push(text);
      } else {
        const [icon, title, ...rest] = text.split('|').map(part => part.trim());
        if (icon && title && rest.length > 0) {
          currentHighlights.push({ icon, title, text: rest.join('|').trim() });
        }
      }
      continue;
    }

    // Recognize section headers
    if (line.startsWith('### Breaking')) {
      currentSection = 'breaking';
      currentChanges.breaking = [];
      continue;
    }
    if (line.startsWith('### Features')) {
      currentSection = 'features';
      currentChanges.features = [];
      continue;
    }
    if (line.startsWith('### Bug Fixes')) {
      currentSection = 'bugFixes';
      currentChanges.bugFixes = [];
      continue;
    }
    if (line.startsWith('### Improvements')) {
      currentSection = 'improvements';
      currentChanges.improvements = [];
      continue;
    }
    if (line.startsWith('### Changes')) {
      currentSection = 'changes';
      currentChanges.changes = [];
      continue;
    }
    if (line.startsWith('### Fixes')) {
      currentSection = 'fixes';
      currentChanges.fixes = [];
      continue;
    }
    if (line.startsWith('### Performance')) {
      currentSection = 'performance';
      currentChanges.performance = [];
      continue;
    }

    // Collect changelog entries
    if (currentSection && line.startsWith('- ')) {
      const changeText = line.substring(2).trim();
      if (changeText) {
        currentChanges[currentSection]?.push(changeText);
      }
    }
  }

  // Save last version
  if (currentVersion) save();

  return entries;
}

function generateChangelogFile(entries: ChangelogEntry[]): string {
  return `// This file is auto-generated by scripts/generate-changelog.ts
// Do not edit manually - changes will be overwritten

export interface ReleaseHighlight {
  /** Lucide icon name. */
  icon: string;
  title: string;
  text: string;
}

export interface ChangelogEntry {
  version: string;
  /** User-facing, shown in the release notes dialog. */
  highlights?: ReleaseHighlight[];
  /** User-facing, shown in the release notes dialog. */
  fixes?: string[];
  changes: {
    breaking?: string[];
    features?: string[];
    bugFixes?: string[];
    improvements?: string[];
    changes?: string[];
    fixes?: string[];
    performance?: string[];
  };
}

export const CHANGELOG_ENTRIES: ChangelogEntry[] = ${JSON.stringify(entries, null, 2)};
`;
}

async function main() {
  try {
    const changelogPath = path.join(__dirname, '..', 'CHANGELOG.md');
    const outputPath = path.join(
      __dirname,
      '..',
      'src',
      'generated',
      'changelog.ts'
    );

    // Ensure output directory exists
    const outputDir = path.dirname(outputPath);
    if (!fs.existsSync(outputDir)) {
      fs.mkdirSync(outputDir, { recursive: true });
    }

    // Read changelog file
    const changelogContent = fs.readFileSync(changelogPath, 'utf-8');

    // Parse changelog
    const entries = parseChangelog(changelogContent);

    // Generate TypeScript file
    const generatedContent = generateChangelogFile(entries);

    // Write generated file
    fs.writeFileSync(outputPath, generatedContent);

    console.log(
      `✅ Generated changelog with ${entries.length} entries at ${outputPath}`
    );
  } catch (error) {
    console.error('❌ Error generating changelog:', error);
    process.exit(1);
  }
}

main();
